import fs from 'node:fs/promises'
import { existsSync, chmodSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFile, spawn } from 'node:child_process'

// Keeping a package running after the terminal closes.
//
// Four backends, in order of preference per platform: systemd --user, launchd,
// schtasks, and a plain detached process as the fallback that always works.
// Every one of them runs the same generated wrapper script, so the environment
// a service sees is the runtime-env.json the install step wrote and nothing
// else — no inherited shell state, no "works in my terminal".

const TASK_FOLDER = '0kay-pm'

function serviceRoot(home) {
  return path.join(home, 'services')
}

function logRoot(home) {
  return path.join(home, 'logs')
}

function systemdDir() {
  return path.join(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config'), 'systemd', 'user')
}

function launchdDir() {
  return path.join(os.homedir(), 'Library', 'LaunchAgents')
}

// ---------------------------------------------------------------------------
// quoting
// ---------------------------------------------------------------------------

export function shellQuote(value) {
  return `'${String(value).replace(/'/g, "'\\''")}'`
}

export function cmdQuote(value) {
  // % is doubled because cmd expands it even inside quotes.
  return `"${String(value).replace(/"/g, '""').replace(/%/g, '%%')}"`
}

// ---------------------------------------------------------------------------
// wrappers
// ---------------------------------------------------------------------------

export function renderPosixWrapper(unit) {
  const extra = (unit.binDirs || []).join(':')
  const pathValue = [extra, process.env.PATH || '/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin']
    .filter(Boolean)
    .join(':')
  const lines = ['#!/bin/sh', '# Generated by 0kay-pm. Do not edit.', `export PATH=${shellQuote(pathValue)}`]
  for (const [key, value] of Object.entries(unit.env || {})) lines.push(`export ${key}=${shellQuote(value)}`)
  lines.push(`cd ${shellQuote(unit.cwd)} || exit 1`)
  lines.push(`exec ${unit.command.map(shellQuote).join(' ')}`)
  return `${lines.join('\n')}\n`
}

export function renderWindowsWrapper(unit) {
  const extra = (unit.binDirs || []).join(';')
  const lines = ['@echo off', 'rem Generated by 0kay-pm. Do not edit.', `set "PATH=${extra};%PATH%"`]
  for (const [key, value] of Object.entries(unit.env || {})) lines.push(`set "${key}=${String(value).replace(/%/g, '%%')}"`)
  lines.push(`cd /d "${unit.cwd}" || exit /b 1`)
  lines.push(unit.command.map(cmdQuote).join(' '))
  return `${lines.join('\r\n')}\r\n`
}

// wscript with a hidden window, so a boot-time task does not flash a console.
export function renderWindowsLauncher(wrapper) {
  const target = String(wrapper).replace(/"/g, '""')
  return `' Generated by 0kay-pm. Do not edit.\r\nCreateObject("WScript.Shell").Run """${target}""", 0, False\r\n`
}

function systemdPath(value) {
  return String(value).replace(/%/g, '%%').replace(/ /g, '\\x20')
}

export function renderSystemdUnit(unit, wrapper) {
  return [
    '[Unit]',
    `Description=0kay-pm: ${unit.name}`,
    'After=network-online.target',
    'Wants=network-online.target',
    '',
    '[Service]',
    'Type=simple',
    `ExecStart=/bin/sh "${systemdPath(wrapper)}"`,
    `WorkingDirectory=${systemdPath(unit.cwd)}`,
    'Restart=always',
    'RestartSec=3',
    'KillMode=mixed',
    '',
    '[Install]',
    'WantedBy=default.target',
    '',
  ].join('\n')
}

export function renderLaunchdPlist(unit, wrapper, logPath) {
  const esc = (value) => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>Label</key><string>com.0kay.${esc(unit.name)}</string>
<key>ProgramArguments</key><array><string>/bin/sh</string><string>${esc(wrapper)}</string></array>
<key>RunAtLoad</key><true/>
<key>KeepAlive</key><true/>
<key>StandardOutPath</key><string>${esc(logPath)}</string>
<key>StandardErrorPath</key><string>${esc(logPath)}</string>
</dict></plist>
`
}


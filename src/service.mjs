function run(file, args, { ignore = false } = {}) {
  return new Promise((resolve) => {
    execFile(file, args, { windowsHide: true }, (error, stdout, stderr) => {
      if (error && !ignore) {
        resolve({ ok: false, error: `${file}: ${stderr || error.message}`.trim() })
        return
      }
      resolve({ ok: true, stdout: String(stdout || '').trim(), stderr: String(stderr || '').trim() })
    })
  })
}

async function materialize(units, ctx) {
  const root = serviceRoot(ctx.home)
  await fs.mkdir(root, { recursive: true })
  await fs.mkdir(logRoot(ctx.home), { recursive: true })
  const prepared = []
  for (const unit of units) {
    const windows = process.platform === 'win32'
    const wrapper = path.join(root, `${unit.name}.${windows ? 'cmd' : 'sh'}`)
    await fs.writeFile(wrapper, windows ? renderWindowsWrapper(unit) : renderPosixWrapper(unit), { mode: 0o755 })
    try {
      chmodSync(wrapper, 0o755)
    } catch {
      // Windows ignores the mode; nothing to do.
    }
    prepared.push({ ...unit, wrapper, log: path.join(logRoot(ctx.home), `${unit.name}.log`) })
  }
  return prepared
}

